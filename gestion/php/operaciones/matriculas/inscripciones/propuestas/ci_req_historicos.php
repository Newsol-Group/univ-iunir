<?php
class ci_req_historicos extends guarani_pers_ci
{
	//-----------------------------------------------------------------------------------
	//---- Eventos ----------------------------------------------------------------------
	//-----------------------------------------------------------------------------------

	function evt__cancelar()
	{
		
	}

	//-----------------------------------------------------------------------------------
	//---- cuadro -----------------------------------------------------------------------
	//-----------------------------------------------------------------------------------

	function conf__cuadro(toba_ei_cuadro $cuadro)
	{
		$persona = toba::memoria()->get_dato('persona');
		$datos = toba::consulta_php('co_requisitos')->get_requisitos_presentados_x_persona($persona);
		$cuadro->set_datos($datos);
	}

	//-----------------------------------------------------------------------------------
	//---- form -------------------------------------------------------------------------
	//-----------------------------------------------------------------------------------

	function conf__form(toba_ei_formulario $form)
	{
		$persona = toba::memoria()->get_dato('persona');
		$datos = toba::consulta_php('co_personas')->get_datos_persona($persona);
		$form->set_datos($datos);
	}

	//-----------------------------------------------------------------------------------
	//---- JAVASCRIPT -------------------------------------------------------------------
	//-----------------------------------------------------------------------------------

	function extender_objeto_js()
	{
		echo "		
			{$this->objeto_js}.evt__cancelar = function()		
			{
				window.close();
			}
		
		";
	}

}
?>